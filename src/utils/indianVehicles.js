export const ALL_BRANDS = Object.keys(INDIAN_VEHICLE_DATABASE);

/**
 * Filter brands matching user's query
 */
export const searchBrands = (query) => {
  if (!query || !query.trim()) return ALL_BRANDS;
  const q = query.trim().toLowerCase();
  const startsWith = ALL_BRANDS.filter(b => b.toLowerCase().startsWith(q));
  const includes = ALL_BRANDS.filter(b => !b.toLowerCase().startsWith(q) && b.toLowerCase().includes(q));
  return [...startsWith, ...includes];
};

/**
 * Get models for a selected brand, filtered by optional query
 */
export const getModelsForBrand = (brandName, query = '') => {
  if (!brandName) return [];
  const matchedBrand = ALL_BRANDS.find(b => b.toLowerCase() === brandName.trim().toLowerCase());
  const models = matchedBrand ? INDIAN_VEHICLE_DATABASE[matchedBrand] : [];
  if (!query || !query.trim()) return models;
  const q = query.trim().toLowerCase();
  const startsWith = models.filter(m => m.toLowerCase().startsWith(q));
  const includes = models.filter(m => !m.toLowerCase().startsWith(q) && m.toLowerCase().includes(q));
  return [...startsWith, ...includes];
};

/**
 * Search all models across all brands
 */
export const searchAllModels = (query = '') => {
  const q = (query || '').trim().toLowerCase();
  const results = [];
  for (const [brand, models] of Object.entries(INDIAN_VEHICLE_DATABASE)) {
    for (const m of models) {
      if (!q || m.toLowerCase().includes(q)) {
        results.push({ brand, model: m });
      }
    }
  }
  return q ? results.slice(0, 25) : results.slice(0, 15);
};

